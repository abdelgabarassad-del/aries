const fs = require('fs');
const path = require('path');

// Read .env if present
const envPath = path.join(__dirname, '.env');
const env = {};

if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, 'utf8');
  content.split('\n').forEach(line => {
    line = line.trim();
    if (line && !line.startsWith('#')) {
      const idx = line.indexOf('=');
      if (idx !== -1) {
        const key = line.slice(0, idx).trim();
        const val = line.slice(idx + 1).trim();
        env[key] = val;
      }
    }
  });
}

// Also read from process.env (for Vercel deployment builds)
const keys = [
  'HERO_IMAGE',
  'PHOTO_1', 'PHOTO_2', 'PHOTO_3', 'PHOTO_4',
  'PHOTO_5', 'PHOTO_6', 'PHOTO_7', 'PHOTO_8',
  'PHOTO_9', 'PHOTO_10', 'PHOTO_11', 'PHOTO_12'
];

keys.forEach(k => {
  if (process.env[k]) {
    env[k] = process.env[k];
  }
});

const output = `// Auto-generated by build.js
window.ENV = ${JSON.stringify(env, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, 'env.js'), output);
console.log('Successfully generated env.js with environment variables.');
